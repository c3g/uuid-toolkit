"""
Enforces the result of validation to be a consistent format and should contain the required fields for the pipeline and front end displa of results.

This module is responsible for receiving a result from the pipeline that was generated by the validate() function and ensure that the following keys are present:
- "valid" : Determines whether an identifier was valid according to each strategy's rules and formats
- "error" : Brief statement of what the error that occured was and will return None if the identifier was valid
- "message" : String message explaining the error or stating that the identifier was valid.

"""

def enforce_validation_result(result: dict) -> dict:
    """
    Enforce the ValidationResult schema.

    Raises ValueError if the schema is invalid.
    """
    if not isinstance(result, dict):
        raise ValueError(
            f"Validation result must be a dict, got {type(result).__name__}"
        )

    required_keys = {"valid", "error", "message"}

    missing = required_keys - result.keys()
    extra = result.keys() - required_keys

    if missing:
        raise ValueError(f"Validation result missing keys: {missing}")

    if extra:
        raise ValueError(f"Validation result has extra keys: {extra}")

    if not isinstance(result["valid"], bool):
        raise ValueError("'valid' must be a boolean")

    if result["error"] is not None and not isinstance(result["error"], str):
        raise ValueError("'error' must be a string or None")

    if not isinstance(result["message"], str):
        raise ValueError("'message' must be a string")


    return result